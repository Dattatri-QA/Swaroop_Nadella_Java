package Day_04;

public class DecrementOperators {

	public static void main(String[] args) {
		int cc = 500;
		int result11 = --cc;
		System.out.println(cc);
		System.out.println(result11);
		System.out.println("*******");

		int a = 10;
		a--;
		System.out.println(a);
		System.out.println("*******");

		int aa = 100;
		int result = aa--;
		System.out.println(result);
		System.out.println(a);
		System.out.println("*******");
	}

}
