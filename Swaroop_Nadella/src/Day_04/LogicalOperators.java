package Day_04;

public class LogicalOperators {

	public static void main(String[] args) {

		// Logical Operators

		boolean a = true;
		boolean b = true;
		boolean boo = a && b;
		System.out.println(boo);
		System.out.println("********");

		boolean aa = true;
		boolean ba = false;
		boolean bo = aa || ba;
		System.out.println(bo);
		System.out.println("********");

		boolean a1 = true;
		boolean result = !a1;
		System.out.println(result);
		System.out.println("********");

	}

}
