package Day_04;

public class RelationalOperators {

	public static void main(String[] args) {

		int a = 10;
		int b = 20;
		boolean bool = a > b;
		System.out.println(bool);
		System.out.println("*********");

		int aa = 20;
		int ba = 10;
		boolean boo = aa >= ba;
		System.out.println(boo);
		System.out.println("*********");

		int c = 5;
		int d = 10;
		boolean bo = c < d;
		System.out.println(bo);
		System.out.println("*********");

		int cc = 20;
		int dd = 10;
		boolean bol = cc <= dd;
		System.out.println(bol);
		System.out.println("*********");

		int cc1 = 20;
		int dd1 = 10;
		boolean bol1 = cc1 != dd1;
		System.out.println(bol1);
		System.out.println("*********");

		int cc10 = 20;
		int dd10 = 10;
		boolean bol10 = cc10 == dd10;
		System.out.println(bol10);
		System.out.println("*********");

	}

}
