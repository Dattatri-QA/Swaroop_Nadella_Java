package Day_04;

public class IncrementOperator {

	public static void main(String[] args) {

		int a = 100;
		a++;
		System.out.println(a);
		System.out.println("*******");

		int aa = 200;
		int result = aa++;
		System.out.println(aa);
		System.out.println(result);
		System.out.println("*******");

		int c = 500;
		int result1 = ++c;
		System.out.println(c);
		System.out.println(result1);
		System.out.println("*******");

	}
}
