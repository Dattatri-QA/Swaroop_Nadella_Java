package Day_06;

public class WhileLoopExample2 {

	public static void main(String[] args) {

		int a = 1;
		while (a <= 10) {
			System.out.println(a);
			a += 2;
		}
		System.out.println();
		int i = 2;
		while (i <= 10) {
			System.out.println(i);
			i += 2;
		}
		System.out.println();
		int ii = 10;
		while (ii >= 1) {
			System.out.println(ii);
			ii--;
		}
	}
}