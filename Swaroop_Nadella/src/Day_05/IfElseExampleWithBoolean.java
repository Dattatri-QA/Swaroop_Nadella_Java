package Day_05;

public class IfElseExampleWithBoolean {

	public static void main(String[] args) {
		boolean bool = false;
		if (bool) {
			System.out.println("First statement");
		} else {
			System.out.println("Secound statement");
		}

		boolean boo = 1 == 2;
		if (boo) {
			System.out.println("If Block");
		} else {
			System.out.println("else block");
		}

	}

}
